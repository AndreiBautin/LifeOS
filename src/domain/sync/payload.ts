/**
 * A batch of changes moving in one direction.
 *
 * Deliberately the same four collections the backup envelope carries, and
 * deliberately *not* the envelope itself — a backup is a complete
 * snapshot with a checksum over the whole of it, and a sync batch is a
 * partial one. Reusing the envelope would have meant a checksum that
 * could not be checked and a "complete" file that was not.
 *
 * Position is absent, as it is from the envelope. It is the one record
 * with no correct last-write-wins answer — two devices advancing a single
 * cursor cannot be reconciled by comparing timestamps — so it stays
 * device-local, which is what makes everything else here safely
 * mergeable.
 */
export interface SyncPayload {
  readonly exercises: readonly Exercise[]
  readonly workouts: readonly WorkoutLog[]
  readonly checkIns: readonly CheckIn[]
  readonly items: readonly Item[]
  readonly projects: readonly Project[]
  readonly upgrades: readonly Upgrade[]
  readonly friends: readonly Friend[]
  readonly metrics: readonly MetricDefinition[]
  readonly reviews: readonly MonthlySnapshot[]
  readonly places: readonly Place[]
  readonly trips: readonly Trip[]
  readonly dailies: readonly Daily[]
  readonly vices: readonly Vice[]
  readonly weighIns: readonly WeighIn[]
  readonly finance: readonly FinanceReading[]
  readonly campaigns: readonly Campaign[]
  /**
   * Ground you have walked, as geohash cells.
   *
   * A grow-only set rather than a collection of records — see
   * `unionCells`. It carries no stamps and no tombstones because neither
   * question arises: two copies are merged by union, and nothing can
   * un-walk ground.
   */
  readonly exploredCells: readonly string[]
  readonly tombstones: readonly Tombstone[]
  /**
   * The travelling half of the settings, when they have changed.
   *
   * One blob rather than a collection, because there is one of them. It
   * is here at all because the program is *derived* from settings — two
   * devices with different tiers derive different programs, so syncing
   * history without the priorities that produced it is the half that only
   * looks like it works.
   *
   * Absent when nothing changed, and absent from anything a build without
   * this sent.
   */
  readonly settings?: SyncedSettings
  /**
   * The resume, when it has changed. The other singleton.
   *
   * It shipped in none of these lists — not the payload, not `isEmpty`,
   * not the backup envelope — so it existed on exactly one device with
   * no copy anywhere, while sync reported success on every run. It is
   * also the single most expensive record here to reproduce: everything
   * else is generated by using the app, and this one was typed in off a
   * PDF.
   *
   * Whole-record last-write-wins on `updatedAt`, which is right for the
   * same reason a weigh-in is: two devices holding a resume hold two
   * opinions about **one** document, so the later one is a correction
   * rather than something to merge. There are no per-day entries to
   * union, unlike a habit's completions.
   */
  readonly resume?: Resume
}

